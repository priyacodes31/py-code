# nested loop
for i in range(3):
    for j in range (3):
        print(i,j)

#nested loop range
for i in range (1,4):
    for j in range (1,4):
        print(i,j)

#nested loop pattern 
for i in range (1,4):
    for j in range (1,4):
        print("*", end = " " )
    print()


#nested loop with numbers 
for i in range (1,5):
    for j in range (1,i+1):
        print(j, end = " ")
    print()

#nested loop with same numbers 
for i in range (1,5):
    for j in range (1,i+1):
        print(i, end = " ")
    print()






    